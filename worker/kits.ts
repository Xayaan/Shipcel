// Exports a starter kit: the kit's own files (kits/<id>.ts) inside what every kit gets: its
// package.json, Wrangler configuration, configuration check, README and GitHub workflows.
import { getFramework, hasKit, type Project } from '../shared/catalog';
import { WRANGLER_VERSION } from '../shared/local-deploy';
import { kits } from '../kits/index.ts';
import type { KitExtras } from '../kits/types.ts';

export type { KitExtras };

const pretty = (value: unknown) => JSON.stringify(value, null, 2) + '\n';

export function generateConfig(
  project: Project,
  extras: KitExtras = {},
): Record<string, unknown> {
  const config: Record<string, unknown> = {
    $schema: 'node_modules/wrangler/config-schema.json',
    name: project.name,
    compatibility_date: '2026-10-07',
    workers_dev: true,
    ...kits[project.framework].config(project, extras),
  };
  // Draft bindings: Wrangler creates and binds these resources on the first deploy.
  if (project.database)
    config.d1_databases = [{ binding: 'DB', migrations_dir: 'migrations' }];
  if (project.storage)
    config.r2_buckets = [
      ...((config.r2_buckets as unknown[] | undefined) ?? []),
      { binding: 'FILES' },
    ];
  return config;
}

export function generateKit(
  project: Project,
  extras: KitExtras = {},
): Record<string, string> {
  if (!hasKit(project.framework))
    throw new Error(
      'This runtime adapter is not ready for starter-kit export.',
    );
  const kit = kits[project.framework];
  const meta = getFramework(project.framework);
  const files: Record<string, string> = {
    'package.json': pretty({
      name: project.name,
      private: true,
      version: '0.1.0',
      type: 'module',
      engines: { node: '>=22.12.0' },
      scripts: kit.scripts,
      dependencies: { ...kit.dependencies },
      devDependencies: { wrangler: WRANGLER_VERSION, ...kit.devDependencies },
      ...(kit.overrides ? { overrides: kit.overrides } : {}),
    }),
    [kit.configFile ?? 'wrangler.json']: pretty(
      generateConfig(project, extras),
    ),
    '.gitignore':
      'node_modules/\ndist/\n.wrangler/\n.env\n.env.*\n.dev.vars\n.dev.vars.*\n' +
      (kit.ignore ?? ''),
    'scripts/check-config.mjs': `import { existsSync, readFileSync } from 'node:fs';
// wrangler.json, or wrangler.jsonc with its comment lines removed.
const file = ['../wrangler.json', '../wrangler.jsonc']
  .map((name) => new URL(name, import.meta.url))
  .find((url) => existsSync(url));
const config = JSON.parse(
  readFileSync(file, 'utf8').replace(/\\/\\*[\\s\\S]*?\\*\\//g, '').replace(/^\\s*\\/\\/.*$/gm, ''),
);
// Bindings without IDs are drafts that Wrangler creates on deploy; placeholder IDs are refused.
for (const db of config.d1_databases || []) {
  if ('database_id' in db && (!/^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$/i.test(db.database_id) || db.database_id === '00000000-0000-0000-0000-000000000000')) {
    console.error('Use a real D1 database_id, or remove it so Wrangler creates the database on deploy. See README.md.');
    process.exit(1);
  }
}
// A Hyperdrive binding names a database added to the project in Shipcel; the placeholder isn't one.
for (const db of config.hyperdrive || []) {
  if (db.id === 'HYPERDRIVE_ID') {
    console.error('Add the Postgres database to the project first (shipcel hyperdrive add DB, or Manage → Database in Shipcel), then put its id in wrangler.json. See README.md.');
    process.exit(1);
  }
}
console.log('Configuration checked. Deploying uses the Cloudflare account selected by Wrangler.');
`,
    ...kit.files(project),
  };

  if (project.database)
    files['migrations/0001_initial.sql'] =
      '-- Initial schema. Add application-specific migrations here.\nCREATE TABLE IF NOT EXISTS app_metadata (key TEXT PRIMARY KEY, value TEXT NOT NULL);\n';

  files['README.md'] = `# ${project.name}

Generated by Shipcel · ${meta.name} · ${meta.runtime}

This is a new starter project, not an import of an existing repository. It contains no account credentials. Shipcel has not created any cloud resources or deployed this app. Review the configuration and commands before running them. Resource creation and deployment can incur charges in your selected Cloudflare account.

## 1. Install and authenticate

Use Node.js 22.12 or newer. In this directory:

\`\`\`sh
npm install
npx wrangler login
npx wrangler whoami
\`\`\`

Confirm the intended account. If you belong to multiple accounts, set \`account_id\` in wrangler.json to the chosen account ID. Never commit API tokens. Keep and commit the generated package-lock.json for reproducible installs.

## 2. Configure resources

${kit.readme.database ?? (project.database ? `The \`DB\` binding in wrangler.json has no database ID. On your first deploy, Wrangler automatically creates a D1 database named after the Worker (\`${project.name}-db\`) and binds it. A local deploy then writes the new ID to wrangler.json; commit or discard it, as future deploys reuse the bound database either way. To use an existing database instead, add its \`database_id\` before deploying. For local development, apply migrations with:\n\n\`\`\`sh\nnpx wrangler d1 migrations apply DB --local\n\`\`\`\n` : 'No SQL database selected.\n')}
${project.storage ? `The \`FILES\` binding has no bucket name. Enable R2 on your account and review its billing requirements first. On your first deploy, Wrangler creates an R2 bucket named after the Worker (\`${project.name}-files\`) and binds it.\n` : 'No object storage selected.\n'}
If a resource name already exists, inspect it before adopting it. Do not delete existing resources to resolve a name conflict. The deploy script refuses placeholder resource IDs.

## 3. Run locally

\`\`\`sh
npm run dev
\`\`\`

${kit.readme.runLocally}
## 4. Deploy to your account

\`\`\`sh
npm run deploy
\`\`\`

${project.database ? `After the first deploy has created the database, review migrations and apply them remotely. They modify your database and are not undone by code rollback.\n\n\`\`\`sh\nnpx wrangler d1 migrations apply DB --remote\n\`\`\`\n\nIf Shipcel's GitHub pipeline deployed this app, review and apply migrations in Shipcel under Manage → Database. It records a Time Travel restore point first. With Wrangler, use the generated database name shown in Shipcel, for example \`npx wrangler d1 migrations apply <database-name> --remote\`.\n` : ''}
Open the URL printed by Wrangler and verify ${kit.readme.verify ?? '\`/api/health\`'}. It is your app's free address, \`https://${project.name}.<your-subdomain>.workers.dev\`, so there is no domain to buy; if your account has no workers.dev subdomain yet, Wrangler offers to register one on the first deploy. Add your own domain later if you want one. Your resources stay in your account even if you stop using Shipcel. Never reuse a production database for untrusted previews.

## Optional GitHub Actions

An example manual workflow is in \`docs/deploy.workflow.yml\`. Commit package-lock.json first. Review the file, copy it to \`.github/workflows/deploy.yml\`, and set repository secrets \`CLOUDFLARE_API_TOKEN\` and \`CLOUDFLARE_ACCOUNT_ID\` in GitHub. The token stays in your GitHub account, never in Shipcel. Scope it to the selected account and only the resources this project needs. Protect the production environment with required reviewers where available. The workflow has no pull-request trigger and does not apply database migrations automatically. Review those separately.

${project.database ? `## Database backups\n\nCloudflare D1 Time Travel keeps point-in-time history (7 days on Workers Free, 30 days on Workers Paid); restore it from Shipcel under Manage → Database or with \`npx wrangler d1 time-travel restore\`. For copies outside Cloudflare, review \`docs/backup.workflow.yml\`, copy it to \`.github/workflows/\`, and set the repository variable \`D1_DATABASE\` to the database name (the generated name shown in Shipcel if its pipeline deployed this app). Exports make the database briefly unavailable.\n\n` : ''}${kit.readme.notes ? `## ${meta.name} on Cloudflare\n\n${kit.readme.notes}\n\n` : ''}## Before production

Add your application's authentication, authorization, input validation, rate limits, backups, and monitoring. Resource bindings are plumbing; this template does not implement user auth, payment processing, database-backed application features, or file upload routes. Existing application code is not copied into this starter. Never overwrite an existing project without reviewing the diff.
`;
  if (project.database)
    files['docs/backup.workflow.yml'] = `name: Back up the D1 database
# Manual by default. The database cannot serve queries while it is exported, so choose a
# quiet time before enabling the schedule. Backups contain your data: keep this repository
# private and limit who can download workflow artifacts.
on:
  workflow_dispatch:
  # schedule:
  #   - cron: '0 3 * * *'
permissions:
  contents: read
jobs:
  backup:
    runs-on: ubuntu-latest
    environment: production
    timeout-minutes: 30
    steps:
      - uses: actions/checkout@v7
      - uses: actions/setup-node@v7
        with:
          node-version: '24'
          cache: npm
      - run: npm ci
      - run: npx wrangler d1 export "${"${{ vars.D1_DATABASE || 'DB' }}"}" --remote --output backup.sql
        env:
          CLOUDFLARE_API_TOKEN: ${'${{ secrets.CLOUDFLARE_API_TOKEN }}'}
          CLOUDFLARE_ACCOUNT_ID: ${'${{ secrets.CLOUDFLARE_ACCOUNT_ID }}'}
      - uses: actions/upload-artifact@v7
        with:
          name: d1-backup
          path: backup.sql
          retention-days: 30
`;
  files['docs/deploy.workflow.yml'] = `name: Deploy to your Cloudflare
on:
  workflow_dispatch:
permissions:
  contents: read
concurrency:
  group: production
  cancel-in-progress: false
jobs:
  deploy:
    runs-on: ubuntu-latest
    environment: production
    timeout-minutes: 15
    steps:
      - uses: actions/checkout@v7
      - uses: actions/setup-node@v7
        with:
          node-version: '24'
          cache: npm
      - run: npm ci
      - run: npm run deploy
        env:
          CLOUDFLARE_API_TOKEN: ${'${{ secrets.CLOUDFLARE_API_TOKEN }}'}
          CLOUDFLARE_ACCOUNT_ID: ${'${{ secrets.CLOUDFLARE_ACCOUNT_ID }}'}
`;
  return files;
}
