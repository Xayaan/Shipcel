// Bundles the shipcel CLI (packages/cli/src) into one file with no runtime dependencies,
// and packs it as public/cli/shipcel.tgz so every Shipcel serves its own CLI:
//   npm install -g https://<your-shipcel>/cli/shipcel.tgz
// Usage: npm run cli:build [-- --check]   (--check: exit 1 when either output is stale)
import { build } from 'esbuild';
import { mkdir, readFile, writeFile, chmod } from 'node:fs/promises';
import { gunzipSync, gzipSync } from 'node:zlib';

const bundlePath = 'packages/cli/dist/shipcel.js';
const tarballPath = 'public/cli/shipcel.tgz';
// The same package at its address before Cloudcel became Shipcel, which `cloudcel upgrade`
// in CLIs installed earlier downloads: it installs shipcel beside the old command.
const earlierTarballPath = 'public/cli/cloudcel.tgz';

const result = await build({
  entryPoints: ['packages/cli/src/main.ts'],
  bundle: true,
  format: 'esm',
  platform: 'node',
  target: 'node20',
  write: false,
  legalComments: 'none',
  charset: 'utf8',
  banner: {
    js: '#!/usr/bin/env node\n// Generated by scripts/build-cli.mjs. Do not edit.',
  },
});
const bundle = result.outputFiles[0].text;

// A plain ustar archive laid out like `npm pack` (everything under package/), with fixed
// times and owners, so the same sources always give the same archive.
function tar(files) {
  const blocks = [];
  for (const { name, data, mode } of files) {
    const header = Buffer.alloc(512);
    const text = (offset, length, value) =>
      header.write(value, offset, length, 'utf8');
    const octal = (offset, length, value) =>
      text(offset, length, `${value.toString(8).padStart(length - 1, '0')}\0`);
    text(0, 100, name);
    octal(100, 8, mode);
    octal(108, 8, 0);
    octal(116, 8, 0);
    octal(124, 12, data.length);
    octal(136, 12, 499162500); // 1985-10-26T08:15:00Z, the time npm pack uses
    header.fill(' ', 148, 156);
    text(156, 1, '0');
    text(257, 6, 'ustar\0');
    text(263, 2, '00');
    const sum = header.reduce((total, byte) => total + byte, 0);
    text(148, 8, `${sum.toString(8).padStart(6, '0')}\0 `);
    blocks.push(header, data, Buffer.alloc((512 - (data.length % 512)) % 512));
  }
  blocks.push(Buffer.alloc(1024));
  return Buffer.concat(blocks);
}
const archive = tar([
  {
    name: 'package/package.json',
    data: await readFile('packages/cli/package.json'),
    mode: 0o644,
  },
  {
    name: 'package/README.md',
    data: await readFile('packages/cli/README.md'),
    mode: 0o644,
  },
  {
    name: 'package/dist/shipcel.js',
    data: Buffer.from(bundle),
    mode: 0o755,
  },
]);

const currentBundle = await readFile(bundlePath, 'utf8').catch(() => null);
const currentArchive = await readFile(tarballPath)
  .then((gz) => gunzipSync(gz))
  .catch(() => null);
const currentEarlier = await readFile(earlierTarballPath)
  .then((gz) => gunzipSync(gz))
  .catch(() => null);
if (process.argv.includes('--check')) {
  if (
    currentBundle !== bundle ||
    !currentArchive?.equals(archive) ||
    !currentEarlier?.equals(archive)
  ) {
    console.error('The CLI build is out of date. Run npm run cli:build.');
    process.exit(1);
  }
  console.log('CLI bundle and package are up to date.');
} else {
  await mkdir('packages/cli/dist', { recursive: true });
  await mkdir('public/cli', { recursive: true });
  if (currentBundle !== bundle) await writeFile(bundlePath, bundle);
  await chmod(bundlePath, 0o755);
  if (!currentArchive?.equals(archive))
    await writeFile(tarballPath, gzipSync(archive, { level: 9 }));
  if (!currentEarlier?.equals(archive))
    await writeFile(earlierTarballPath, gzipSync(archive, { level: 9 }));
  console.log(
    `CLI: ${Math.round(bundle.length / 1024)} KB, packed as ${tarballPath}.`,
  );
}
