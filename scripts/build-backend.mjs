// Bundles the sign-in and realtime service (services/backend) into
// worker/generated/backend.ts: the script Shipcel uploads, its D1 schema and a version.
// Usage: npm run backend:build [-- --check]   (--check: exit 1 when the bundle is stale)
import { build } from 'esbuild';
import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';

const target = 'worker/generated/backend.ts';
const result = await build({
  entryPoints: ['services/backend/src/index.ts'],
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2022',
  external: ['cloudflare:workers'],
  write: false,
  legalComments: 'none',
  charset: 'utf8',
});
const script = result.outputFiles[0].text;
const schema = await readFile('services/backend/schema.sql', 'utf8');
const version = createHash('sha256')
  .update(script)
  .update(schema)
  .digest('hex')
  .slice(0, 12);
const output = `// Generated by scripts/build-backend.mjs from services/backend. Do not edit.
export const backendVersion = ${JSON.stringify(version)};
export const backendSchema = ${JSON.stringify(schema)};
export const backendScript = ${JSON.stringify(script)};
`;
const current = await readFile(target, 'utf8').catch(() => null);
if (process.argv.includes('--check')) {
  if (current !== output) {
    console.error(`${target} is out of date. Run npm run backend:build.`);
    process.exit(1);
  }
  console.log('Backend bundle is up to date.');
} else {
  await mkdir('worker/generated', { recursive: true });
  if (current !== output) await writeFile(target, output);
  console.log(`Backend ${version}: ${Math.round(script.length / 1024)} KB.`);
}
