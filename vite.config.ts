import { defineConfig, type Plugin } from 'vite';
import react from '@vitejs/plugin-react';
import { cloudflare } from '@cloudflare/vite-plugin';

// While `npm run dev` runs, so does the Worker's minute schedule, as Cloudflare runs it for a
// deployed Shipcel: deployments advance, health checks and the budget guard run, and
// notifications go out with no dashboard open. CLOUDCEL_LOCAL_CRON=off turns it off (the
// browser tests do).
const MINUTE = 60_000;
function minuteSchedule(): Plugin {
  return {
    name: 'shipcel-minute-schedule',
    apply: 'serve',
    configureServer(server) {
      if (process.env.CLOUDCEL_LOCAL_CRON === 'off') return;
      const timer = setInterval(() => {
        const address = server.httpServer?.address();
        if (!address || typeof address === 'string') return;
        fetch(
          `http://127.0.0.1:${address.port}/cdn-cgi/handler/scheduled?cron=*+*+*+*+*`,
        )
          .then((response) => response.body?.cancel())
          .catch(() => {
            /* The next minute tries again. */
          });
      }, MINUTE);
      timer.unref();
      server.httpServer?.once('close', () => clearInterval(timer));
    },
  };
}

export default defineConfig({
  plugins: [react(), cloudflare(), minuteSchedule()],
  server: { port: 5173, strictPort: true },
  // The dashboard lives at /app/. The public site (/, /pricing/, /why/, /compare/…) is
  // static HTML in public/, generated by scripts/build-site.mjs.
  environments: {
    client: { build: { rollupOptions: { input: { app: 'app/index.html' } } } },
  },
});
